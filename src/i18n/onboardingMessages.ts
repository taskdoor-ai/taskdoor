export type OnboardingMessageKey = keyof typeof onboardingEn;
export const onboardingZh: Record<OnboardingMessageKey, string> = Object.fromEntries(Object.keys(onboardingEn).map(key => [key, key])) as Record<OnboardingMessageKey, string>;
export function onboardingTranslator(locale: Locale) {
  return (key: OnboardingMessageKey, values: Record<string, string | number> = {}) => {
    const template = locale === "zh-CN" ? onboardingZh[key] : onboardingEn[key];
    return template.replace(/\{(\w+)\}/g, (match, name: string) => Object.hasOwn(values, name) ? String(values[name]) : match);
  };
}
/** Translate known transition errors at display time, retaining unknown server details. */
export function localizeOnboardingMessage(locale: Locale, message: string): string {
  if (!Object.hasOwn(onboardingEn, message)) return message;
  return onboardingTranslator(locale)(message as OnboardingMessageKey);
}
