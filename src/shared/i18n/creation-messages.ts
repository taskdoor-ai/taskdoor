export function creationTranslator(locale: Locale) { return (key: CreationMessageKey, values: Record<string, string | number | undefined> = {}) => (locale === "zh-CN" ? creationZh[key] : creationEn[key]).replace(/\{(\w+)\}/g, (match, name: string) => Object.hasOwn(values, name) ? String(values[name] ?? "") : match); }
/** Only display-layer system messages use this adapter; business fields never pass through it. */
export function localizeCreationMessage(locale: Locale, value: string | null | undefined): string {
  if (!value) return "";
  const keys = Object.keys(creationZh) as CreationMessageKey[];
  const key = keys.find(key => creationZh[key] === value || creationEn[key] === value);
  if (key) return creationTranslator(locale)(key);
  const patterns = [...keys].sort((a, b) => creationZh[b].replace(/\{\w+\}/g, "").length - creationZh[a].replace(/\{\w+\}/g, "").length);
  for (const key of patterns) {
    for (const source of [creationZh[key], creationEn[key]]) {
      if (!source.includes("{")) continue;
      const names: string[] = [];
      const expression = source.split(/(\{\w+\})/g).map(part => {
        if (/^\{\w+\}$/.test(part)) { names.push(part.slice(1, -1)); return "(.+?)"; }
        return part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      }).join("");
      const match = new RegExp(`^${expression}$`).exec(value);
      if (!match) continue;
      const values = Object.fromEntries(names.map((name, index) => [name, match[index + 1]]));
      if (values.label && locale === "en") values.label = values.label.replace(/^任务$/, "task").replace(/^子任务 (\d+)$/, "subtask $1");
      return creationTranslator(locale)(key, values);
    }
  }
  return value;
}
export function useCreationI18n() { const { locale } = useI18n(); return { locale, c: creationTranslator(locale), localize: (value: string | null | undefined) => localizeCreationMessage(locale, value) }; }
