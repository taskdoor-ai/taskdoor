type ModuleKey = keyof typeof moduleEn;
export function moduleText(locale: 'en' | 'zh-CN', value: string) {
  const key = (Object.keys(moduleEn) as ModuleKey[]).find(key => moduleZh[key] === value || moduleZh[key].replaceAll("职责", "责任") === value || moduleEn[key] === value);
  return key ? (locale === 'en' ? moduleEn[key] : moduleZh[key]) : value;
}
export function useModuleCopy() {
  const { locale } = useI18n();
  const copy = (key: ModuleKey, values: Record<string, string | number> = {}) => (locale === 'en' ? moduleEn[key] : moduleZh[key]).replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  return Object.assign(copy, { text: (value: string) => moduleText(locale, value) });
}
